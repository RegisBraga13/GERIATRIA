// A historia clinica que o medico escreve nao pode ser trocada pelo modelo
// local. Ate 11/09/2026 era: qualquer texto que comecasse com "Paciente " ou
// tivesse "Quanto ao " casava com os padroes de texto antigo, e ao salvar o
// texto dele virava o modelo, sem aviso.
//
// Rodar a partir da raiz do projeto:
//     node --test 'testes/js/*.test.js'
import assert from "node:assert/strict";
import { describe, it } from "node:test";

import { buildEvolutionNarrative, evolutionNeedsRebuild, evolutionSuggestionOnAiFailure, teleconsultationText } from "../../src/clinical/narrative.js";
import { TELECONSULTA_CONSENTIMENTO } from "../../src/clinical/vocabulary.js";

const MARIA = { nome: "Maria Silva", nascimento: "1984-03-10", sexo: "Feminino" };

describe("texto do medico fica como ele escreveu", () => {
  it("o que comeca com 'Paciente' nao e remontado", () => {
    assert.equal(evolutionNeedsRebuild({ id: "c1", evolution: "Paciente retorna com melhora parcial do humor.", evolutionAutoGenerated: false }), false);
  });

  it("'Quanto ao' no meio do texto dele tambem nao", () => {
    assert.equal(evolutionNeedsRebuild({ id: "c1", evolution: "Melhora parcial. Quanto ao sono, dorme bem.", evolutionAutoGenerated: false }), false);
  });

  it("retorno dele que abre com o nome do paciente fica", () => {
    assert.equal(evolutionNeedsRebuild({ id: "r1", type: "return", evolution: "Maria Silva retorna estavel.", evolutionAutoGenerated: false }, MARIA), false);
  });
});

describe("texto do modelo continua sendo remontado", () => {
  it("com a marca do modelo", () => {
    assert.equal(evolutionNeedsRebuild({ id: "c1", evolution: "Maria Silva, 42 anos, com queixa de insônia.", evolutionAutoGenerated: true }), true);
  });

  it("vazio", () => {
    assert.equal(evolutionNeedsRebuild({ id: "c1", evolution: "", evolutionAutoGenerated: false }), true);
  });

  it("rascunho novo sem marca: e o texto que o modelo pos na tela", () => {
    assert.equal(evolutionNeedsRebuild({ evolution: "Maria Silva, 42 anos, com queixa de insônia." }), true);
  });
});

describe("registro salvo antes da marca segue a regra antiga", () => {
  it("texto antigo reconhecido pelos padroes e remontado", () => {
    assert.equal(evolutionNeedsRebuild({ id: "c1", evolution: "Paciente refere tristeza ha 3 meses." }), true);
  });

  it("texto que nao casa com padrao nenhum fica", () => {
    assert.equal(evolutionNeedsRebuild({ id: "c1", evolution: "Refere melhora do sono." }), false);
  });

  it("retorno antigo que abre com o nome do paciente e remontado", () => {
    assert.equal(evolutionNeedsRebuild({ id: "r1", type: "return", evolution: "Maria Silva retorna estavel." }, MARIA), true);
  });
});

describe("teleconsulta na historia clinica", () => {
  it("presencial nao ganha frase", () => {
    assert.equal(teleconsultationText({ consultationMode: "IN_PERSON" }), "");
    assert.equal(teleconsultationText({}), "");
  });

  it("com consentimento e local", () => {
    assert.equal(
      teleconsultationText({ consultationMode: "TELECONSULTATION", teleconsultaConsentimento: [TELECONSULTA_CONSENTIMENTO], teleconsultaLocalPaciente: "Recife/PE" }),
      "Atendimento por telemedicina, com o paciente em Recife/PE. Consentimento do paciente registrado."
    );
  });

  it("sem consentimento marcado a frase diz isso, em vez de calar", () => {
    assert.equal(
      teleconsultationText({ consultationMode: "TELECONSULTATION" }),
      "Atendimento por telemedicina. Consentimento do paciente não registrado."
    );
  });

  it("hibrido", () => {
    assert.match(teleconsultationText({ consultationMode: "HYBRID" }), /^Atendimento híbrido, em parte por telemedicina\./);
  });

  it("entra na narrativa logo depois da abertura", () => {
    const texto = buildEvolutionNarrative({ queixa: "Insonia", consultationMode: "TELECONSULTATION" }, MARIA);
    assert.equal(texto.split("\n\n")[1], "Atendimento por telemedicina. Consentimento do paciente não registrado.");
  });
});

describe("IA fora do ar na Evolucao: o texto do medico fica", () => {
  const erro = new Error("limite de requisicoes");

  it("texto escrito por ele nao e trocado pelo modelo local", () => {
    const alvo = { id: "c1", evolution: "Melhora parcial do humor, dorme melhor.", evolutionAutoGenerated: false, evolucaoOrigem: "medico" };
    const sugestao = evolutionSuggestionOnAiFailure({ target: alvo, patient: MARIA, error: erro });
    assert.equal("evolution" in sugestao, false);
    assert.equal("evolucaoOrigem" in sugestao, false);
    assert.equal("evolutionAutoGenerated" in sugestao, false);
    assert.match(sugestao.aiStatus, /limite de requisicoes/);
    assert.match(sugestao.aiStatus, /mantido/);
  });

  it("a fonte do texto que ele revisa continua a mesma", () => {
    const alvo = { id: "c1", evolution: "Texto da IA que ele revisou.", evolutionAutoGenerated: false, evolucaoOrigem: "rag" };
    const sugestao = evolutionSuggestionOnAiFailure({ target: alvo, patient: MARIA, error: erro });
    assert.equal("ragSourcesEvolucao" in sugestao, false);
  });

  it("campo vazio recebe o modelo local, marcado como tal", () => {
    const sugestao = evolutionSuggestionOnAiFailure({ target: { evolution: "" }, patient: MARIA, error: erro });
    assert.ok(sugestao.evolution.length > 0);
    assert.equal(sugestao.evolutionAutoGenerated, true);
    assert.equal(sugestao.evolucaoOrigem, "local");
    assert.deepEqual(sugestao.ragSourcesEvolucao, []);
    assert.match(sugestao.aiStatus, /Evolução local aplicada/);
  });

  it("texto que o proprio modelo montou pode ser refeito", () => {
    const alvo = { evolution: "Texto antigo do modelo.", evolutionAutoGenerated: true, evolucaoOrigem: "local" };
    const sugestao = evolutionSuggestionOnAiFailure({ target: alvo, patient: MARIA, error: erro });
    assert.equal(sugestao.evolutionAutoGenerated, true);
    assert.ok(sugestao.evolution);
  });
});
